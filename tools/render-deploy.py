#!/usr/bin/env python3
"""Regenerate compatibility manifests; deploy/ is the only source of truth."""
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
TARGETS = {'kube/deploy.yaml': 'deploy/legacy/core',
           'kube/default-scheduler.yaml': 'deploy/default-scheduler',
           **{f'kube/operators/{c}.yaml': f'deploy/legacy/{c}'
              for c in ('cronjob', 'external-dns', 'acme', 'postgres', 'helm')}}
HEADER = '# Generated by python3 tools/render-deploy.py; edit deploy/ instead.\n'

def rendered(source):
    return HEADER + subprocess.check_output(['kubectl', 'kustomize', source], cwd=ROOT, text=True)

if __name__ == '__main__':
    for target, source in TARGETS.items():
        content = rendered(source)
        if '--check' in sys.argv:
            if (ROOT / target).read_text() != content:
                sys.exit(f'{target} is stale; run python3 tools/render-deploy.py')
        else:
            (ROOT / target).write_text(content)
