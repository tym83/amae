#!/usr/bin/env python3
"""Taintednetes: pods find their nodes the way people find each other.

Every pod and every node is a soul. A pod proposes to the nodes it likes,
in order. A node keeps the best pod that has asked so far, says "no" to
the rest and, when someone better comes, tells its current pod to go and
wounds it in parting. A pod gives its heart to the node that takes it, so
the wound leaves a scar but does not close it to the world.

There is no controller and no loop that compares the cluster with a
desired state. The cluster settles when every soul is waiting for someone
and nobody has anything left to say: that silence is a stable matching.

Cluster format:
    pod web: n1 n2 n3     the nodes web would live on, best first
    node n1: db web       the pods n1 would host, best first
"""
import io
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import tainted  # noqa: E402


def parse(text):
    pods, nodes = {}, {}
    for raw in text.splitlines():
        line = raw.split('#', 1)[0].strip()
        if not line:
            continue
        head, _, prefs = line.partition(':')
        kind, name = head.split()
        target = pods if kind == 'pod' else nodes if kind == 'node' else None
        if target is None:
            raise ValueError(f"unknown kind '{kind}'")
        if name in tainted.KEYWORDS or name in pods or name in nodes:
            raise ValueError(f"'{name}' cannot be a name here")
        target[name] = prefs.split()
    return pods, nodes


def generate(pods, nodes):
    out = ["# generated by tools/taintednetes.py"]
    for pod, prefs in pods.items():
        out += ["", f"soul {pod}"] + [f"    meet {n}" for n in nodes]
        for n in prefs:
            out += [f"    tell {n} \"{pod}\"", f"    hear {n} into answer",
                    "    if answer == \"yes\"", f"        give heart to {n}",
                    f"        say \"{pod} settles on {n}\"", f"        hear {n} into news",
                    f"        say \"{pod} is sent away from {n}\"", "    end"]
        out += [f"    say \"{pod} has nowhere to live\"", "end"]
    for node, prefs in nodes.items():
        out += ["", f"soul {node}"] + [f"    meet {p}" for p in pods]
        out += ["    mark listen", "    hear anyone into p"]
        for rank, pod in enumerate(prefs):
            better, worse = prefs[:rank], prefs[rank + 1:]
            out.append(f"    if p == \"{pod}\"")
            if better:
                cond = " or ".join(f"trust {b} == 1" for b in better)
                out += [f"        if {cond}", f"            tell {pod} \"no\"",
                        "            return to listen", "        end"]
            out += [f"        tell {pod} \"yes\"", f"        warm to {pod}"]
            for w in worse:
                out += [f"        if trust {w} == 1", f"            cool to {w}",
                        f"            tell {w} \"go\"", f"            wound {w}", "        end"]
            out += ["        return to listen", "    end"]
        for pod in pods:
            if pod not in prefs:
                out += [f"    if p == \"{pod}\"", f"        tell {pod} \"no\"", "    end"]
        out += ["    return to listen", "end"]
    return "\n".join(out) + "\n"


def settle(pods, nodes, runs=0):
    """Run the cluster until it falls silent and read where every pod lives."""
    out = io.StringIO()
    world = tainted.World(tainted.compile_program(generate(pods, nodes)),
                          runs=runs, out=out, err=io.StringIO())
    code = world.run()
    if code != 2:
        raise RuntimeError(f"the cluster did not settle (exit {code})")
    placement = {}
    for pod in pods:
        ins = world.souls[pod].current()
        placement[pod] = ins[2] if ins and ins[0] == 'hear' else None
    return placement, out.getvalue().splitlines(), world


def gale_shapley(pods, nodes):
    """Reference: pod-proposing deferred acceptance."""
    rank = {n: {p: i for i, p in enumerate(prefs)} for n, prefs in nodes.items()}
    holder, nxt, free = {}, {p: 0 for p in pods}, list(pods)
    while free:
        p = free.pop(0)
        while nxt[p] < len(pods[p]):
            n = pods[p][nxt[p]]
            nxt[p] += 1
            if p not in rank[n]:
                continue
            cur = holder.get(n)
            if cur is None or rank[n][p] < rank[n][cur]:
                holder[n] = p
                if cur is not None:
                    free.append(cur)
                break
    placement = {p: None for p in pods}
    for n, p in holder.items():
        placement[p] = n
    return placement


def main(argv):
    if not argv or argv[0] in ('-h', '--help'):
        print("usage: taintednetes.py [--emit] cluster.taintednetes", file=sys.stderr)
        return 64
    with open(argv[-1]) as f:
        pods, nodes = parse(f.read())
    if '--emit' in argv:
        sys.stdout.write(generate(pods, nodes))
        return 0
    placement, events, world = settle(pods, nodes)
    for line in events:
        print(line)
    print()
    for pod, node in placement.items():
        moves = sum(len(world.rel(pod, n).scars) for n in nodes)
        where = f"lives on {node}" if node else "has nowhere to live"
        print(f"{pod} {where}; sent away {moves} time(s)")
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
