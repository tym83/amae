#!/usr/bin/env python3
"""Compile a Minsky counter machine into a Tainted program.

Each counter is a soul, and its value is how much the machine trusts it.
`warm to` increments, `cool to` decrements, `trust x == 0` tests for zero.
The machine never stores anything in memory, so nothing can fade:
two trust counters are already enough for Turing completeness.

Machine format, one instruction per line:
    counters a b          names of the counters
    init a=3 b=4          optional starting values
    L: inc a M            a += 1, go to M
    L: dec a M Z          if a == 0 go to Z, else a -= 1 and go to M
    L: halt               stop and print every counter
Execution starts at the first instruction.
"""
import sys


def parse(text):
    counters, init, prog, entry = [], {}, {}, None
    for raw in text.splitlines():
        line = raw.split('#', 1)[0].strip()
        if not line:
            continue
        words = line.split()
        if words[0] == 'counters':
            counters = words[1:]
        elif words[0] == 'init':
            for pair in words[1:]:
                name, value = pair.split('=')
                init[name] = int(value)
        else:
            label = words[0].rstrip(':')
            prog[label] = tuple(words[1:])
            entry = entry or label
    return counters, init, prog, entry


def compile_machine(counters, init, prog, entry):
    out = ["# generated by tools/minsky.py", 'written by "minsky"', "soul machine"]
    for c in counters:
        out.append(f"    meet {c}")
    for c in counters:
        out += [f"    warm to {c}"] * init.get(c, 0)
    out.append(f"    return to at_{entry}")
    for label, ins in prog.items():
        out.append(f"    mark at_{label}")
        if ins[0] == 'inc':
            out += [f"    warm to {ins[1]}", f"    return to at_{ins[2]}"]
        elif ins[0] == 'dec':
            out += [f"    if trust {ins[1]} == 0", f"        return to at_{ins[3]}",
                    "    end", f"    cool to {ins[1]}", f"    return to at_{ins[2]}"]
        elif ins[0] == 'halt':
            out += [f"    say \"{c} = \" + trust {c}" for c in counters]
            out.append("    goodbye")
        else:
            raise ValueError(f"unknown instruction {ins}")
    out.append("end")
    for c in counters:
        out += ["", f"soul {c}", "    meet machine", "end"]
    return "\n".join(out) + "\n"


def simulate(counters, init, prog, entry, limit=1_000_000):
    regs = {c: init.get(c, 0) for c in counters}
    pc = entry
    for _ in range(limit):
        ins = prog[pc]
        if ins[0] == 'halt':
            return regs
        if ins[0] == 'inc':
            regs[ins[1]] += 1
            pc = ins[2]
        elif regs[ins[1]] == 0:
            pc = ins[3]
        else:
            regs[ins[1]] -= 1
            pc = ins[2]
    return None


if __name__ == '__main__':
    with open(sys.argv[1]) as f:
        sys.stdout.write(compile_machine(*parse(f.read())))
